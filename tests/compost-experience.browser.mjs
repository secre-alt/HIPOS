import {chromium,expect} from '@playwright/test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdir} from 'node:fs/promises';

const server=spawn(process.execPath,['scripts/serve-pwa.mjs'],{windowsHide:true,stdio:'pipe',env:{...process.env,PORT:'4188'}});
let browser;
try {
  await new Promise((resolve,reject)=>{server.stdout.on('data',d=>{if(d.toString().includes('http://localhost'))resolve();});server.stderr.on('data',d=>process.stderr.write(d));server.once('exit',c=>reject(Error('Server exited '+c)));});
  browser=await chromium.launch({channel:process.env.PW_CHANNEL||'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await mkdir('test-results',{recursive:true});
  await page.goto('http://localhost:4188/#compost');
  await page.locator('[data-compost-start]').waitFor();
  await page.evaluate(()=>{Math.random=()=>0.5;});
  await page.clock.install();
  const x=()=>page.locator('#compost-basket').evaluate(el=>parseFloat(el.style.left));
  const visit=async route=>{await page.evaluate(route=>{location.hash=route;},route);await page.locator(route==='games'?'.games-grid':route==='sort'?'#sort-game':'#compost-game').waitFor();};
  await page.locator('[data-compost-start]').click();
  await page.keyboard.press('Space');await expect(page.locator('.compost-paused')).toBeVisible();
  await page.keyboard.press('Escape');await expect(page.locator('.compost-paused')).toHaveCount(0);
  await expect(page.locator('#compost-field')).toBeFocused();
  await page.keyboard.down('ArrowRight');await page.clock.runFor(300);
  assert.ok(await x()>65,'holding an arrow moves continuously');
  await page.keyboard.up('ArrowRight');const released=await x();await page.clock.runFor(200);
  assert.equal(await x(),released,'keyup stops movement');
  await page.keyboard.down('ArrowLeft');await page.clock.runFor(100);
  await page.locator('#compost-hud [data-compost-pause]').click();
  const paused=await x(),falling=await page.locator('.compost-item').first().getAttribute('style');
  await page.keyboard.up('ArrowLeft');await page.clock.runFor(300);
  assert.equal(await x(),paused);assert.equal(await page.locator('.compost-item').first().getAttribute('style'),falling);
  await expect(page.locator('.compost-paused')).toContainText('Paused');
  await expect(page.locator('#compost-basket')).toBeVisible();
  await page.locator('.compost-paused button').click();await page.clock.runFor(200);
  assert.equal(await x(),paused,'resume does not reuse a held key or move the basket');

  const recenter=await page.locator('#compost-field').boundingBox();
  await page.mouse.click(recenter.x+recenter.width*.3,recenter.y+recenter.height*.4);
  const right=await page.locator('[data-compost-right]').boundingBox();
  await page.mouse.move(right.x+right.width/2,right.y+right.height/2);await page.mouse.down();
  const tapped=await x();await page.clock.runFor(250);
  assert.ok(await x()>tapped+10,'holding a movement button continues past the first step');
  await page.mouse.move(2,2);await page.mouse.up();
  const pointerReleased=await x();await page.clock.runFor(200);
  assert.equal(await x(),pointerReleased,'release outside the button stops captured input');
  await page.locator('[data-compost-left]').dispatchEvent('pointerdown',{pointerId:17,button:0,isPrimary:true});
  await page.clock.runFor(150);
  await page.locator('[data-compost-left]').dispatchEvent('pointercancel',{pointerId:17});
  const cancelled=await x();await page.clock.runFor(200);assert.equal(await x(),cancelled,'pointer cancellation stops movement');

  const field=await page.locator('#compost-field').boundingBox();
  await page.mouse.move(field.x+field.width*.2,field.y+field.height*.4);await page.mouse.down();
  await page.mouse.move(field.x+field.width*.8,field.y+field.height*.4);await page.mouse.up();
  assert.ok(Math.abs(await x()-80)<1,'dragging follows the captured pointer');
  await page.keyboard.down('ArrowLeft');await page.clock.runFor(100);
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  const blurred=await x();await page.clock.runFor(200);assert.equal(await x(),blurred,'blur clears held input');
  await page.keyboard.up('ArrowLeft');

  await page.keyboard.down('ArrowRight');await visit('games');await page.keyboard.up('ArrowRight');await visit('compost');
  await page.locator('[data-compost-start]').click();await page.clock.runFor(1000);
  assert.equal(await x(),50,'navigation clears movement');
  const regularY=await page.locator('.compost-item').first().evaluate(el=>parseFloat(el.style.top));
  await visit('games');await visit('compost');
  await page.selectOption('#compost-pace','practice');await page.locator('[data-compost-start]').click();
  await expect(page.locator('#compost-pace')).toBeDisabled();
  await page.clock.runFor(1000);
  assert.ok(await page.locator('.compost-item').first().evaluate(el=>parseFloat(el.style.top))<regularY-3,'practice scraps fall more slowly');
  await page.clock.runFor(39000);
  await expect(page.locator('.compost-done h3')).toHaveText('You caught 18 of 18 compostable scraps.');
  await expect(page.locator('.compost-done')).toContainText('Practice pace');
  await expect(page.locator('#compost-count')).toHaveText('18/18');
  await expect(page.locator('.compost-plastic-result')).toHaveCount(0);
  await expect(page.locator('#compost-pace')).toBeEnabled();
  await expect(page.locator('#compost-pace')).toHaveValue('practice');
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('hipos.buddy.v1')));
  assert.equal(saved.compost,1);assert.equal(saved.treats,1,'practice uses existing daily rewards');
  await page.evaluate(()=>{const language=document.querySelector('#language');language.value='fil';language.dispatchEvent(new Event('change'));});
  await expect(page.locator('.compost-done')).toContainText('Bilis para sa pagsasanay');
  await page.evaluate(()=>{const language=document.querySelector('#language');language.value='en';language.dispatchEvent(new Event('change'));});

  for(const [width,height] of [[390,844],[1280,844],[568,320]])for(const theme of ['light','dark']) {
    await page.setViewportSize({width,height});
    await page.evaluate(theme=>{document.documentElement.dataset.theme=theme;},theme);
    await visit('games');await visit('compost');
    await page.locator('[data-compost-start]').click();await page.clock.runFor(1000);
    const fits=await page.evaluate(()=>{const field=document.querySelector('#compost-field').getBoundingClientRect(),controls=document.querySelector('#compost-controls').getBoundingClientRect(),nav=document.querySelector('.mobile-bottom-nav').getBoundingClientRect();return field.top>=document.querySelector('aside').getBoundingClientRect().bottom&&controls.bottom<=(nav.height?nav.top:innerHeight)+1;});
    assert.ok(fits,'field and movement controls fit at '+width+'x'+height);
    await page.locator('#compost-hud [data-compost-pause]').click();
    const frozenCount=await page.locator('.compost-item').count();assert.ok(frozenCount>0);
    await page.clock.runFor(300);await expect(page.locator('.compost-item')).toHaveCount(frozenCount);
    await expect(page.locator('.compost-paused button')).toBeFocused();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:`test-results/compost-pause-${width}-${theme}.png`});
  }
  await visit('games');await visit('compost');
  await page.evaluate(()=>{Math.random=()=>0.99;});await page.selectOption('#compost-pace','regular');
  await page.locator('[data-compost-start]').click();await page.clock.runFor(30000);
  await expect(page.locator('.compost-plastic-result strong')).toHaveText('18/18');
  await page.locator('[data-compost-start]').click();
  const centered=await page.locator('#compost-field').boundingBox();
  await page.mouse.click(centered.x+centered.width*.99,centered.y+centered.height*.4);await page.clock.runFor(30000);
  await expect(page.locator('.compost-plastic-result strong')).toHaveText('0/18');
  await visit('sort');await page.locator('[data-sort-bin="yes"]').click();
  await expect(page.locator('.sort-bin.is-answer')).toHaveCount(1);
  await expect(page.locator('.sort-bin.is-answer')).toHaveAccessibleName(/Correct destination/);
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto('http://localhost:4188/#compost');await mobile.locator('[data-compost-start]').click();
  const touch=await mobile.context().newCDPSession(mobile),mx=()=>mobile.locator('#compost-basket').evaluate(el=>parseFloat(el.style.left));
  const left=await mobile.locator('[data-compost-left]').boundingBox();
  await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:left.x+left.width/2,y:left.y+left.height/2,id:1}]});
  await mobile.waitForTimeout(250);assert.ok(await mx()<35,'native touch holds move continuously');
  await touch.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});
  const touchCancelled=await mx();await mobile.waitForTimeout(150);assert.equal(await mx(),touchCancelled,'native touch cancellation stops movement');
  const mobileField=await mobile.locator('#compost-field').boundingBox();
  await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:mobileField.x+mobileField.width*.2,y:mobileField.y+mobileField.height*.4,id:2}]});
  await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:mobileField.x+mobileField.width*.8,y:mobileField.y+mobileField.height*.4,id:2}]});
  await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  assert.ok(Math.abs(await mx()-80)<1,'native touch dragging follows the basket position');
  await mobile.close();
  assert.deepEqual(errors,[]);
  console.log('PASS: held keyboard/buttons, native touch, pointer cancellation, pause/resume, practice pace, rewards, and correct-destination feedback');
} finally {await browser?.close();server.kill();}
